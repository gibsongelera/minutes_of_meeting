  function translateString(text, dict) {
    if (!text) return text;
    let result = text;
    // Sort keys by length desc so multi-word phrases match first
    const keys = Object.keys(dict).sort((a, b) => b.length - a.length);
    for (const k of keys) {
      const re = new RegExp('\\b' + k.replace(/[-/\\^$*+?.()|[\]{}]/g, '\\$&') + '\\b', 'gi');
      result = result.replace(re, (m) => {
        const tr = dict[k];
        if (m[0] === m[0].toUpperCase()) return tr[0].toUpperCase() + tr.slice(1);
        return tr;
      });
    }
    return result;
  }

